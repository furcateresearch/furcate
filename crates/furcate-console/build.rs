//! Generate the console's layout from the manifest that declares it.
//!
//! `deploy/os/arms.toml` says what the parts of Furcate are, which app shows
//! each one and which section of it. Three things need that: the desktop
//! launcher, the documentation, and this console. The launcher already reads
//! the file. The console used to restate it — `Pane::Power => &[Draw,
//! Cooling]` beside a manifest saying Power contains energy and thermal — and
//! two statements of one fact is one that will eventually be wrong.
//!
//! Generating it here rather than reading the file at runtime means the drift
//! is a compile error rather than a screen that quietly lost a section, and
//! costs nothing on a machine that is running.
//!
//! If the manifest is unreadable this fails the build. That is deliberate: a
//! console built without knowing what is in it would come up with empty apps,
//! which is a worse outcome than not building.

use std::collections::BTreeMap;
use std::path::PathBuf;

fn main() {
    // Walk up for the manifest rather than counting "..". Counting encodes the
    // crate's depth in the tree into the build, and it silently became wrong the
    // moment crates moved from crates/<crate> to crates/<side>/<crate> for the
    // licence split — the build failed with a NotFound that named the file but
    // not the reason. Searching upward cannot rot that way.
    let manifest = {
        let mut dir = PathBuf::from(env!("CARGO_MANIFEST_DIR"));
        loop {
            let candidate = dir.join("deploy/os/arms.toml");
            if candidate.exists() {
                break candidate.canonicalize().expect("the manifest path resolves");
            }
            if !dir.pop() {
                panic!("deploy/os/arms.toml not found in any ancestor of the console crate");
            }
        }
    };
    println!("cargo:rerun-if-changed={}", manifest.display());

    let text = std::fs::read_to_string(&manifest).expect("the manifest is readable");

    // app -> sections, in the order the manifest declares them. The order is
    // the reading order on screen, so it is the manifest's to decide.
    let mut order: Vec<String> = Vec::new();
    let mut by_app: BTreeMap<String, Vec<String>> = BTreeMap::new();

    for block in text.split("[[arm]]").skip(1) {
        let field = |key: &str| -> String {
            block
                .lines()
                .find(|l| l.trim_start().starts_with(&format!("{key} =")))
                .and_then(|l| l.split_once('='))
                .map(|(_, v)| v.trim().trim_matches('"').to_string())
                .unwrap_or_default()
        };
        let (view, section) = (field("view"), field("section"));
        if view.is_empty() || section.is_empty() {
            continue;
        }
        if !order.contains(&view) {
            order.push(view.clone());
        }
        let list = by_app.entry(view).or_default();
        // An arm shown in a section another arm already claimed does not repeat
        // it: identity and authority could share one, and the section is drawn
        // once regardless of how many arms it serves.
        if !list.contains(&section) {
            list.push(section);
        }
    }

    let variant = |s: &str| -> String {
        s.split(|c: char| !c.is_alphanumeric())
            .filter(|w| !w.is_empty())
            .map(|w| {
                let mut c = w.chars();
                match c.next() {
                    Some(f) => f.to_uppercase().collect::<String>() + c.as_str(),
                    None => String::new(),
                }
            })
            .collect()
    };

    let mut out = String::from(
        "// Generated by build.rs from deploy/os/arms.toml. Do not edit.\n\
         impl Pane {\n    \
         /// What is inside this app, in the order the manifest declares it.\n    \
         pub fn sections(&self) -> &'static [Section] {\n        \
         match self {\n",
    );
    for app in &order {
        let sections = by_app.get(app).expect("an app in the order has sections");
        let list: Vec<String> = sections.iter().map(|s| format!("Section::{}", variant(s))).collect();
        out.push_str(&format!(
            "            Pane::{} => &[{}],\n",
            variant(app),
            list.join(", ")
        ));
    }
    // Deliberately no wildcard arm. Every app is declared in the manifest
    // today, which clippy proved by calling the fallback unreachable — so
    // leaving it out turns "somebody added an app and forgot to declare what is
    // in it" into a non-exhaustive match, which the compiler will not accept.
    // A silent empty app is the failure this whole file exists to prevent.
    out.push_str("        }\n    }\n}\n");

    let dest = PathBuf::from(std::env::var("OUT_DIR").expect("OUT_DIR")).join("sections.rs");
    std::fs::write(&dest, out).expect("the generated table is writable");
}
