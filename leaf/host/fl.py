#!/usr/bin/env python3
"""Furcate leaf node host tool (development registry and node).

  fl.py keys                       create the development keys in the Secure Enclave
  fl.py pin                        write provision/fl_pinned_keys.h (public keys only)
  fl.py grant NODE ROLES GEN       operator-sign a grant for a node key -> state/grants/NODE.grant
  fl.py model-release TFLITE ID VER ...  release-sign a model manifest -> registry/
  fl.py fw-release BIN SEQ [--signer IDX:CMD]...  release-sign a firmware image -> registry/
  fl.py info                       open a session and print the leaf's info

Keys: every private key is a Secure Enclave key reached through `fl-se`.
In this development setup the operator, both release signers and the node
are separate enclave keys on one Mac. In a deployment the operator key is a
passkey, the release signers are TPM keys on different machines, and the
node key is that node's own TPM key.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import time
import os
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
import fl_proto as P  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
STATE = Path(os.environ.get("FL_STATE", Path.home() / ".furcate-leaf"))
REGISTRY = Path(os.environ.get("FL_REGISTRY", STATE / "registry"))
KEYS = {"operator": "fl-operator", "release_a": "fl-release-a", "release_b": "fl-release-b",
        "node": "fl-node", "rogue": "fl-rogue"}
RELEASE_KEYS = [KEYS["release_a"], KEYS["release_b"]]
PORT = os.environ.get("FL_PORT", "/dev/cu.usbserial-0001")


def cmd_keys(a):
    import subprocess
    for k in KEYS.values():
        r = subprocess.run([P.FL_SE, "create", k], capture_output=True, text=True)
        print(k, "created" if r.returncode == 0 else r.stderr.strip())


def c_array(b: bytes) -> str:
    return "{" + ", ".join(f"0x{x:02x}" for x in b) + "}"


def cmd_pin(a):
    # The operator key may live on another machine (e.g. a server TPM); its
    # public key is then passed in, and only public keys are written.
    ops = [bytes.fromhex(h) for h in a.operator_pub] if a.operator_pub else [P.se_pub(KEYS["operator"])]
    rel = [bytes.fromhex(h) for h in a.release_pub] if a.release_pub else [P.se_pub(k) for k in RELEASE_KEYS]
    out = ["// Generated by host/fl.py pin. Public keys only.", "#pragma once", "#include <stdint.h>", "",
           f"#define FL_PINNED_OPERATOR_COUNT {len(ops)}",
           f"#define FL_PINNED_RELEASE_COUNT {len(rel)}",
           f"#define FL_PINNED_RELEASE_THRESHOLD {a.threshold}",
           f"#define FL_PINNED_MIN_GENERATION {a.min_generation}", "",
           "static const uint8_t FL_PINNED_OPERATOR[][65] = {",
           *[f"    {c_array(k)}," for k in ops], "};",
           "static const uint8_t FL_PINNED_RELEASE[][65] = {",
           *[f"    {c_array(k)}," for k in rel], "};", ""]
    p = ROOT / "provision" / "fl_pinned_keys.h"
    p.write_text("\n".join(out))
    print("wrote", p)


def grant_path(node: str) -> Path:
    return STATE / "grants" / f"{node}.grant.json"


def cmd_grant(a):
    roles = 0
    for r in a.roles.split(","):
        roles |= P.ROLES[r]
    node_pub = P.se_pub(a.node)
    leaf = bytes.fromhex(a.leaf) if a.leaf else bytes(32)
    g = P.make_grant(node_pub, roles, a.generation, leaf)
    signer = a.signer or KEYS["operator"]
    sig = P.se_sign(signer, g)
    p = grant_path(a.node)
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(json.dumps({"grant": g.hex(), "sig": sig.hex(), "roles": a.roles, "generation": a.generation,
                             "signed_by": signer}, indent=1))
    print("wrote", p)


def load_grant(node: str) -> tuple[bytes, bytes]:
    j = json.loads(grant_path(node).read_text())
    return bytes.fromhex(j["grant"]), bytes.fromhex(j["sig"])


def release_sign(body: bytes, signers: list[str]) -> bytes:
    sigs = [(RELEASE_KEYS.index(s) if s in RELEASE_KEYS else 7, P.se_sign(s, body)) for s in signers]
    return P.envelope(body, sigs)


def model_body(blob: bytes, *, mid: str, version: int, arena_kb: int, input_hwc: tuple[int, int, int],
               labels: str, st_seed: int, st_expect: bytes, st_tol: int = 2, ops: bytes = b"",
               targets=("esp32",), runtime="tflm", runtime_min=1, needs_psram=0, sha=None, size=None,
               licence="Apache-2.0", pre="gray,96x96,int8", post="argmax") -> bytes:
    h, w, c = input_hwc
    t = P.tlv
    body = (t(P.M["KIND"], b"\x01") + t(P.M["ID"], mid) + t(P.M["VERSION"], version) +
            t(P.M["SIZE"], size if size is not None else len(blob)) +
            t(P.M["SHA256"], sha if sha is not None else hashlib.sha256(blob).digest()) +
            t(P.M["RUNTIME"], runtime) + t(P.M["RUNTIME_MIN"], runtime_min) +
            b"".join(t(P.M["TARGET"], x) for x in targets) + t(P.M["ARENA_KB"], arena_kb, 2) +
            t(P.M["NEEDS_PSRAM"], bytes([needs_psram])) +
            t(P.M["INPUT"], h.to_bytes(2, "big") + w.to_bytes(2, "big") + c.to_bytes(2, "big") + b"\x01") +
            t(P.M["LABELS"], labels) + t(P.M["PRE"], pre) + t(P.M["POST"], post) + t(P.M["ST_SEED"], st_seed) +
            t(P.M["ST_EXPECT"], st_expect) + t(P.M["ST_TOL"], bytes([st_tol])) + t(P.M["POLICY"], b"\x00") +
            t(P.M["LICENCE"], licence))
    if ops:
        body += t(P.M["OPS"], ops)
    return body


def firmware_body(blob: bytes, seq: int, targets=("esp32",)) -> bytes:
    t = P.tlv
    return (t(P.M["KIND"], b"\x02") + t(P.M["ID"], "furcate-leaf") + t(P.M["VERSION"], seq) +
            t(P.M["SIZE"], len(blob)) + t(P.M["SHA256"], hashlib.sha256(blob).digest()) +
            b"".join(t(P.M["TARGET"], x) for x in targets))


def cmd_signed(body: bytes, signers: list[str]) -> bytes:
    """Release signatures from commands, one per pinned release key:
    'INDEX:COMMAND' where COMMAND reads the body on stdin and prints a DER
    signature (hex), e.g. '0:ssh <signer-host> fl-tpm sign <release-key>'."""
    import shlex
    import subprocess
    sigs = []
    for spec in signers:
        idx, _, cmd = spec.partition(":")
        out = subprocess.check_output(shlex.split(cmd), input=body).decode().strip().split()[-1]
        sigs.append((int(idx), bytes.fromhex(out)))
    return P.envelope(body, sigs)


def cmd_fw_release(a):
    blob = Path(a.bin).read_bytes()
    body = firmware_body(blob, a.seq)
    env = cmd_signed(body, a.signer) if a.signer else release_sign(body, RELEASE_KEYS)
    REGISTRY.mkdir(parents=True, exist_ok=True)
    out = REGISTRY / f"firmware-seq{a.seq}"
    (out.with_suffix(".bin")).write_bytes(blob)
    (out.with_suffix(".manifest")).write_bytes(env)
    print("wrote", out)


def cmd_model_release(a):
    blob = Path(a.tflite).read_bytes()
    body = model_body(blob, mid=a.id, version=a.version, arena_kb=a.arena_kb, input_hwc=tuple(a.input),
                      labels=a.labels, st_seed=a.st_seed,
                      st_expect=bytes(int(x) & 0xFF for x in a.st_expect.split(",")), st_tol=a.st_tol)
    env = release_sign(body, a.signers.split(",") if a.signers else RELEASE_KEYS)
    REGISTRY.mkdir(parents=True, exist_ok=True)
    out = REGISTRY / f"model-{a.id}-v{a.version}"
    out.with_suffix(".tflite").write_bytes(blob)
    out.with_suffix(".manifest").write_bytes(env)
    print("wrote", out)


def cmd_info(a):
    link = P.Serial(PORT, log=(print if a.verbose else None))
    g, s = load_grant(KEYS["node"])
    ses = P.Session.open(link, KEYS["node"], g, s)
    t, f = ses.call(P.INFO_REQ)
    print(json.dumps({k: [x.hex() if not x.isascii() else x.decode(errors="replace") for x in v]
                      for k, v in f.items()}, indent=1))
    ses.call(P.BYE)


def cmd_rollover(a):
    """Asks the leaf for its identity rollover record (old identifier-derived key and
    new eFuse-HMAC key both sign), adds the operator countersignature made in the
    operator's hardware key, and checks the result with the parent-side verifier."""
    import fl_rollover as R
    link = P.Serial(PORT, log=(print if a.verbose else None))
    g, s = load_grant(KEYS["node"])
    ses = P.Session.open(link, KEYS["node"], g, s)
    assurance = (P.one(ses.evidence, 4, b"") or b"").decode()
    now = int(time.time())
    t, f = ses.call(P.ROLLOVER_REQ, P.tlv(P.T_ROLL_SEQ, a.seq, 4), P.tlv(P.T_NOT_BEFORE, now.to_bytes(8, "big")),
                    P.tlv(P.T_NOT_AFTER, (now + a.days * 86400).to_bytes(8, "big")))
    ses.call(P.BYE)
    if t != P.ROLLOVER or P.one(f, P.T_OK) != b"\x01":
        sys.exit("leaf refused: " + (P.one(f, P.T_REASON, b"?")).decode())
    rec = P.one(f, P.T_RECORD)
    body = rec[:R.BODY_LEN]
    der = P.se_sign(KEYS["operator"], b"furcate-leaf rollover v1 operator\n" + body)
    rec = rec[:-1] + bytes([len(der)]) + der
    old_pub, new_pub = rec[4:69], rec[69:134]
    if new_pub != ses.leaf_pub:
        sys.exit("record successor is not the key of this session")
    pol = R.Policy(now=now, old_id=R.leaf_id(old_pub), roster_old_level=1, proven_new_level=R.level(assurance),
                   operator_pubs=[P.se_pub(KEYS["operator"])])
    why = R.verify(rec, pol)
    out = STATE / "rollover" / f"{R.leaf_id(old_pub).hex()[:32]}-to-{R.leaf_id(new_pub).hex()[:32]}.fli1"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_bytes(rec)
    print(json.dumps({"old_id": R.leaf_id(old_pub).hex()[:32], "new_id": R.leaf_id(new_pub).hex()[:32],
                      "assurance": assurance, "verify": why or "accepted", "record": str(out),
                      "sha256": hashlib.sha256(rec).hexdigest()}, indent=1))


def _escrow_session(a):
    link = P.Serial(PORT, log=(print if a.verbose else None))
    g, s = load_grant(KEYS["node"])
    ses = P.Session.open(link, KEYS["node"], g, s)
    return ses, P.one(ses.evidence, 1, b"")  # evidence tag 1 is the eFuse MAC


def _escrow_dir() -> Path:
    d = STATE / "escrow"
    d.mkdir(parents=True, exist_ok=True)
    return d


def _escrow_finish(ses, t, f, what):
    ses.call(P.BYE)
    ok = t == P.ESCROW and P.one(f, P.T_OK) == b"\x01"
    print(json.dumps({"op": what, "ok": ok, "reason": (P.one(f, P.T_REASON, b"") or b"").decode() or None,
                      "detail": (P.one(f, P.T_DETAIL, b"") or b"").decode() or None}, indent=1))
    return ok, f


def cmd_escrow_export(a):
    """Asks the classic leaf for its helper data export, checks the leaf's signature and
    keeps the message under ~/.furcate-leaf/escrow/."""
    import fl_puf_escrow as E
    ses, mac = _escrow_session(a)
    t, f = ses.call(P.ESCROW_EXPORT_REQ)
    ok, f = _escrow_finish(ses, t, f, "escrow-export")
    if not ok:
        sys.exit(1)
    msg = P.one(f, P.T_RECORD)
    why, leaf_id, mac2, blob = E.verify_export(msg, ses.leaf_pub, 0x3FFDF000)
    if why:
        sys.exit("export refused by the parent check: " + why)
    out = _escrow_dir() / f"{leaf_id.hex()[:32]}.fhx1"
    out.write_bytes(msg)
    print(json.dumps({"leaf_id": leaf_id.hex()[:32], "mac": mac2.hex(), "blob_digest": E.blob_digest(blob).hex(),
                      "message_sha256": hashlib.sha256(msg).hexdigest(), "file": str(out)}, indent=1))


def cmd_escrow_adopt(a):
    import fl_puf_escrow as E
    ses, mac = _escrow_session(a)
    body = b"FHA1" + mac + ses.leaf_id + a.seq.to_bytes(4, "big")
    der = P.se_sign(KEYS["operator"], body)
    t, f = ses.call(P.ESCROW_ADOPT, P.tlv(P.T_RECORD, body + bytes([len(der)]) + der))
    ok, _ = _escrow_finish(ses, t, f, "escrow-adopt")
    sys.exit(0 if ok else 1)


def cmd_escrow_restore(a):
    import fl_puf_escrow as E
    msg = Path(a.export_file).read_bytes()
    blob = msg[E.EXPORT_BODY + 64:]
    ses, mac = _escrow_session(a)
    replace = bytes.fromhex(a.replace_id) if a.replace_id else ses.leaf_id
    body = b"FHR1" + mac + replace + msg[4:36] + E.blob_digest(blob) + a.seq.to_bytes(4, "big")
    der = P.se_sign(KEYS["operator"], body)
    t, f = ses.call(P.ESCROW_RESTORE, P.tlv(P.T_RECORD, body + bytes([len(der)]) + der + blob))
    ok, _ = _escrow_finish(ses, t, f, "escrow-restore")
    sys.exit(0 if ok else 1)


def main():
    ap = argparse.ArgumentParser()
    sp = ap.add_subparsers(dest="cmd", required=True)
    sp.add_parser("keys")
    p = sp.add_parser("pin")
    p.add_argument("--threshold", type=int, default=2)
    p.add_argument("--min-generation", type=int, default=1)
    p.add_argument("--operator-pub", action="append", help="operator public key (hex), repeatable")
    p.add_argument("--release-pub", action="append",
                   help="release public key (hex), repeatable; the order sets the signer index")
    p = sp.add_parser("rollover")
    p.add_argument("seq", type=int)
    p.add_argument("--days", type=int, default=3)
    p.add_argument("-v", "--verbose", action="store_true")
    p = sp.add_parser("escrow-export")
    p.add_argument("-v", "--verbose", action="store_true")
    p = sp.add_parser("escrow-adopt")
    p.add_argument("seq", type=int)
    p.add_argument("-v", "--verbose", action="store_true")
    p = sp.add_parser("escrow-restore")
    p.add_argument("export_file")
    p.add_argument("seq", type=int)
    p.add_argument("--replace-id", help="64 hex digits: the enrolment this command may replace (default: the leaf's current id)")
    p.add_argument("-v", "--verbose", action="store_true")
    p = sp.add_parser("grant")
    p.add_argument("node")
    p.add_argument("roles")
    p.add_argument("generation", type=int)
    p.add_argument("--leaf")
    p.add_argument("--signer")
    p = sp.add_parser("fw-release")
    p.add_argument("bin")
    p.add_argument("seq", type=int)
    p.add_argument("--signer", action="append",
                   help="INDEX:COMMAND release signer (e.g. a TPM on another host); default: the SE keys")
    p = sp.add_parser("model-release")
    p.add_argument("tflite")
    p.add_argument("id")
    p.add_argument("version", type=int)
    p.add_argument("--arena-kb", type=int, required=True)
    p.add_argument("--input", type=int, nargs=3, default=[96, 96, 1])
    p.add_argument("--labels", required=True)
    p.add_argument("--st-seed", type=int, required=True)
    p.add_argument("--st-expect", required=True, help="comma-separated int8 outputs from the reference interpreter")
    p.add_argument("--st-tol", type=int, default=2)
    p.add_argument("--signers", help="comma-separated release key names (default: both)")
    p = sp.add_parser("info")
    p.add_argument("-v", "--verbose", action="store_true")
    a = ap.parse_args()
    {"keys": cmd_keys, "pin": cmd_pin, "grant": cmd_grant, "fw-release": cmd_fw_release,
     "model-release": cmd_model_release, "info": cmd_info, "rollover": cmd_rollover, "escrow-export": cmd_escrow_export, "escrow-adopt": cmd_escrow_adopt, "escrow-restore": cmd_escrow_restore}[a.cmd](a)


if __name__ == "__main__":
    main()
